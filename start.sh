#!/bin/bash
# =====================================================================
# Запуск sysadmin-usb на Linux.
# Использует системный Python 3.
# =====================================================================

# Проверяем, что Python 3 установлен
if ! command -v python3 &> /dev/null; then
    echo "[ERROR] Python 3 не найден. Установи: sudo apt install python3"
    exit 1
fi

# Запускаем приложение
python3 app/main.py

# Пауза (если запущено двойным кликом)
read -p "Нажми Enter для выхода..."
